CREATE TABLE promo_codes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code text NOT NULL UNIQUE CHECK (code ~ '^[A-Z0-9_-]{3,32}$'),
 percentage integer NOT NULL CHECK (percentage BETWEEN 1 AND 99),
 enabled boolean NOT NULL,
 target text NOT NULL CHECK (target IN ('all', 'selected')),
 minimum_eligible_subtotal_kopecks bigint CHECK (minimum_eligible_subtotal_kopecks > 0),
 maximum_discount_kopecks bigint CHECK (maximum_discount_kopecks > 0),
 starts_at timestamptz, ends_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (ends_at > starts_at)
);
