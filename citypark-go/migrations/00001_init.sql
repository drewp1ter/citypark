-- Target PostgreSQL 17 schema for citypark-go.
-- This is the design reference. The executable copy is migrations/00001_init.sql (task 07).
--
-- Conventions:
--   * money is stored as integer kopecks in *_kopecks columns
--   * sale_start / sale_end are minutes from midnight (NULL = no time restriction)
--   * sale_days is '' (no day restriction) or 7 chars of 0/1, Monday first
--   * updated_at is set by the queries (SET updated_at = now()), there are no triggers

CREATE TABLE users (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    name                 text NOT NULL,
    email                text UNIQUE,
    phone                text NOT NULL UNIQUE,
    password_hash        text NOT NULL DEFAULT '',
    legacy_password_hash text NOT NULL DEFAULT '',
    role                 text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_email_confirmed   boolean NOT NULL DEFAULT false,
    is_phone_confirmed   boolean NOT NULL DEFAULT false
);

CREATE TABLE addresses (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    city       text NOT NULL,
    address    text NOT NULL,
    UNIQUE (city, address)
);

CREATE TABLE user_addresses (
    user_id    bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    address_id bigint NOT NULL REFERENCES addresses (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, address_id)
);

CREATE TABLE categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    iiko_id     text UNIQUE,
    sort_order  integer NOT NULL DEFAULT 0,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    is_deleted  boolean NOT NULL DEFAULT false,
    sale_start  integer CHECK (sale_start BETWEEN 0 AND 1439),
    sale_end    integer CHECK (sale_end BETWEEN 0 AND 1440),
    sale_days   text NOT NULL DEFAULT '' CHECK (sale_days ~ '^([01]{7})?$'),
    search      tsvector GENERATED ALWAYS AS (to_tsvector('russian', name)) STORED
);
CREATE INDEX categories_search_idx ON categories USING gin (search);

CREATE TABLE category_images (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    category_id bigint NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    url         text NOT NULL UNIQUE,
    type        text NOT NULL DEFAULT ''
);
CREATE INDEX category_images_category_id_idx ON category_images (category_id);

CREATE TABLE products (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    iiko_id       text UNIQUE,
    category_id   bigint NOT NULL REFERENCES categories (id),
    sort_order    integer NOT NULL DEFAULT 0,
    name          text NOT NULL,
    description   text NOT NULL DEFAULT '',
    measure_unit  text NOT NULL DEFAULT '',
    weight        double precision NOT NULL DEFAULT 0 CHECK (weight >= 0),
    proteins      double precision NOT NULL DEFAULT 0,
    fats          double precision NOT NULL DEFAULT 0,
    carbohydrates double precision NOT NULL DEFAULT 0,
    calories      double precision NOT NULL DEFAULT 0,
    flags         integer NOT NULL DEFAULT 0,
    price_kopecks bigint NOT NULL CHECK (price_kopecks >= 0),
    is_deleted    boolean NOT NULL DEFAULT false,
    sale_start    integer CHECK (sale_start BETWEEN 0 AND 1439),
    sale_end      integer CHECK (sale_end BETWEEN 0 AND 1440),
    sale_days     text NOT NULL DEFAULT '' CHECK (sale_days ~ '^([01]{7})?$'),
    search        tsvector GENERATED ALWAYS AS (to_tsvector('russian', name)) STORED
);
CREATE INDEX products_category_id_idx ON products (category_id);
CREATE INDEX products_search_idx ON products USING gin (search);

CREATE TABLE product_images (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    url        text NOT NULL UNIQUE,
    type       text NOT NULL DEFAULT ''
);
CREATE INDEX product_images_product_id_idx ON product_images (product_id);

CREATE TABLE tags (
    id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag text NOT NULL UNIQUE
);

CREATE TABLE product_tags (
    product_id bigint NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    tag_id     bigint NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, tag_id)
);
CREATE INDEX product_tags_tag_id_idx ON product_tags (tag_id);

CREATE TABLE delivery_prices (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    name          text NOT NULL UNIQUE,
    value         text NOT NULL DEFAULT '',
    price_kopecks bigint NOT NULL CHECK (price_kopecks >= 0)
);

CREATE TABLE orders (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now(),
    customer_id            bigint NOT NULL REFERENCES users (id),
    address_id             bigint REFERENCES addresses (id) ON DELETE SET NULL,
    status                 text NOT NULL DEFAULT 'new'
                           CHECK (status IN ('new', 'pending', 'paid', 'canceled', 'confirmed')),
    comment                text NOT NULL DEFAULT '',
    payment_type           text NOT NULL CHECK (payment_type IN ('cash', 'online')),
    items_hash             text NOT NULL,
    payment_id             text NOT NULL DEFAULT '',
    delivery_price_kopecks bigint NOT NULL DEFAULT 0 CHECK (delivery_price_kopecks >= 0)
);
CREATE INDEX orders_customer_id_idx ON orders (customer_id);
CREATE INDEX orders_payment_id_idx ON orders (payment_id);

CREATE TABLE order_items (
    order_id              bigint NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id            bigint NOT NULL REFERENCES products (id),
    amount                integer NOT NULL DEFAULT 1 CHECK (amount > 0),
    offered_price_kopecks bigint NOT NULL CHECK (offered_price_kopecks >= 0),
    PRIMARY KEY (order_id, product_id)
);
CREATE INDEX order_items_product_id_idx ON order_items (product_id);

