import assert from 'node:assert/strict'
import { chromium } from 'playwright'
import { seedCart } from '../menu-cart.mjs'

const base = (process.env.BASE_URL ?? 'http://localhost:3111').replace(/\/+$/, '')
const browser = await chromium.launch({ headless: true })
const cart = await seedCart([1])

try {
 const worker = await (await fetch(`${base}/sw.js`)).text()
 assert.match(worker, /pathname\.startsWith\('\/mini'\)/)
 console.log('Service worker excludes private Mini App routes: PASS')
 for (const theme of ['light', 'dark']) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  await context.addInitScript(({ cart, theme }) => { localStorage.setItem('citypark-cart', JSON.stringify(cart)); localStorage.setItem('theme', theme) }, { cart, theme })
  const page = await context.newPage()
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.abort())
  for (const path of ['/mini/account', '/mini/orders', '/mini/orders/1', '/mini/checkout/done?MNT_TRANSACTION_ID=1', '/mini/checkout?payment=failed&MNT_TRANSACTION_ID=1']) {
   const response = await page.goto(base + path)
   assert.equal(response.status(), 200, path)
   await page.getByText('Откройте приложение через Telegram').waitFor()
   assert.equal(await page.getByText('Заказ № 1').count(), 0, path)
   assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, path)
  }
  await page.goto(base + '/checkout/done?MNT_TRANSACTION_ID=1&surface=mini&status=paid')
  await page.getByText('Не удалось проверить оплату. Корзина сохранена.').waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('citypark-cart')), JSON.stringify(cart))
  await page.reload()
  assert.equal(await page.evaluate(() => localStorage.getItem('citypark-cart')), JSON.stringify(cart))
  await page.goto(base + '/checkout?payment=failed&MNT_TRANSACTION_ID=1&surface=mini')
  assert.equal(new URL(page.url()).pathname, '/checkout')
  assert.equal(await page.evaluate(() => localStorage.getItem('citypark-cart')), JSON.stringify(cart))
  console.log(`${theme}: unauthenticated mini routes, forged return, reload and cart preservation PASS`)
  await context.close()
 }
 if (process.env.QA_MINI_SESSION) {
  const context = await browser.newContext()
  const origin = new URL(base)
  await context.addCookies([{ name: '__Host-citypark_mini', value: process.env.QA_MINI_SESSION, domain: origin.hostname, path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }])
  const page = await context.newPage()
  await page.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ status: 200, contentType: 'application/javascript', body: 'window.Telegram={WebApp:{initData:"read-only",ready(){},expand(){}}}' }))
  await page.goto(base + '/mini/account')
  await page.getByRole('heading', { name: 'Аккаунт Telegram' }).waitFor()
  await page.getByRole('link', { name: 'История заказов' }).click()
  await page.getByRole('heading', { name: 'История заказов' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Подтвердить связь' }).count(), 0)
  console.log('Authenticated mini account and owned history read-only PASS')
  await context.close()
 } else console.log('QA_MINI_SESSION absent: authenticated read-only checks skipped')
 if (process.env.QA_CUSTOMER_WRITES === '1') {
  assert.ok(process.env.QA_MINI_SESSION && process.env.QA_WEB_SESSION, 'Live pairing needs QA_MINI_SESSION and QA_WEB_SESSION')
  const origin = new URL(base)
  const mini = await browser.newContext()
  const web = await browser.newContext()
  await mini.addCookies([{ name: '__Host-citypark_mini', value: process.env.QA_MINI_SESSION, domain: origin.hostname, path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }])
  await web.addCookies([{ name: '__Host-citypark_customer', value: process.env.QA_WEB_SESSION, domain: origin.hostname, path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }])
  const miniPage = await mini.newPage()
  await miniPage.route('https://telegram.org/js/telegram-web-app.js', route => route.fulfill({ status: 200, contentType: 'application/javascript', body: 'window.Telegram={WebApp:{initData:"read-only",ready(){},expand(){}}}' }))
  const webPage = await web.newPage()
  await miniPage.goto(base + '/mini/account')
  await webPage.goto(base + '/account')
  await miniPage.getByRole('button', { name: 'Создать код' }).click()
  const canceledCode = await miniPage.locator('strong').first().textContent()
  assert.match(canceledCode, /^[A-Za-z0-9_-]{22}$/)
  await miniPage.getByRole('button', { name: 'Отменить' }).click()
  await webPage.getByRole('textbox', { name: 'Код из Telegram' }).fill(canceledCode)
  await webPage.getByRole('button', { name: 'Продолжить' }).click()
  await webPage.getByText('Код недействителен или устарел').waitFor()
  await miniPage.getByRole('button', { name: 'Создать новый код' }).click()
  const code = await miniPage.locator('strong').first().textContent()
  assert.match(code, /^[A-Za-z0-9_-]{22}$/)
  await webPage.getByRole('textbox', { name: 'Код из Telegram' }).fill(code)
  await webPage.getByRole('button', { name: 'Продолжить' }).click()
  await webPage.getByRole('button', { name: 'Подтвердить связь' }).click()
  await miniPage.getByRole('button', { name: 'Подтвердить связь' }).waitFor({ timeout: 15_000 })
  await miniPage.getByRole('button', { name: 'Подтвердить связь' }).click()
  await miniPage.getByText('Связь подтверждена. Откройте приложение заново').waitFor()
  await webPage.goto(base + '/account/orders')
  await webPage.getByRole('heading', { name: 'История заказов' }).waitFor()
  console.log('Live canceled-code rejection, two confirmations, source reauthentication and website owned history PASS')
  console.log('PENDING: provider payment and cross-app navigation require manual device checks; this flow created no order or payment')
  await mini.close()
  await web.close()
 } else console.log('Live stale/conflict/replay, pairing, order and payment writes require QA_CUSTOMER_WRITES=1 and owner-provided sessions')
} finally {
 await browser.close()
}
